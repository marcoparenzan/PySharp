import numpy as np
import pandas as pd

s = pd.Series(pd.date_range('2020-01-01', periods=4, freq='D'))
v = s.values
print(v, v.dtype, type(v).__name__)
print(repr(v))
print(np.asarray(s), np.array(s).dtype)
print(s.to_numpy(), s.to_numpy().dtype)
print(pd.DatetimeIndex(['2020-01-01', '2020-06-01']).values)
print(pd.DatetimeIndex(['2020-01-01', '2020-06-01']).to_numpy())
td = pd.Series(pd.to_timedelta([1, 2, 3], unit='h'))
print(td.values, td.values.dtype, repr(td.values))
print(td.values.sum(), td.values / np.timedelta64(1, 'h'), td.values.astype('timedelta64[m]'))
print(v[1], v[1] - v[0], (v[3] - v[0]) / np.timedelta64(1, 'D'))
print(v.max(), v.min(), np.sort(v)[::-1])
print(pd.Series(v), pd.Series(v).dtype)
print(pd.Series(np.array(['2020-01-01', '2020-02-01'], dtype='datetime64[D]')))
print(pd.Series(np.array(['2020-01-01', '2020-02-01'], dtype='datetime64[ns]')))
print(pd.DatetimeIndex(np.array(['2020-01-01', '2020-02-01'], dtype='datetime64[ns]')))
print(pd.to_datetime(np.array(['2020-01-01', '2020-02-01'], dtype='datetime64[s]')))
print(pd.Series(np.array([1, 2, 3], dtype='timedelta64[s]')))
print(pd.DataFrame({'d': v, 'x': [1, 2, 3, 4]}))
print(pd.DataFrame({'d': v})['d'].dt.year.tolist())
print(v > np.datetime64('2020-01-02'))
print((s > np.datetime64('2020-01-02')).tolist())
print(s + np.timedelta64(1, 'D'))
print(s - np.datetime64('2020-01-01'))
print(s == np.datetime64('2020-01-03'))
print(np.datetime64('2020-01-01') == pd.Timestamp('2020-01-01'))
print(pd.Timestamp(np.datetime64('2020-03-04T05:06:07')))
print(pd.Timedelta(np.timedelta64(90, 'm')))
print(pd.to_datetime(np.datetime64('2020-03-04')))
print(pd.Series([pd.NaT, pd.Timestamp('2020-01-01')]).values)
print(pd.Series(pd.to_datetime(['2020-01-01 10:20:30.123456789'])).values)
two = pd.DataFrame({'a': v, 'b': v + np.timedelta64(1, 'D')})
print(two.values.shape, two.values.dtype)
print(two.values[1])
