# concat
s1 = pd.Series([1, 2], index=['a', 'b'], name='s')
s2 = pd.Series([3, 4], index=['c', 'd'], name='s')
print(pd.concat([s1, s2]))
print(pd.concat([s1, s2], ignore_index=True))
print(pd.concat([s1, s2], keys=['one', 'two']))
print(pd.concat([s1, s2.rename('t')], axis=1))
print(pd.concat([pd.Series([1, 2]), pd.Series([3, 4])], axis=1))
f1 = pd.DataFrame({'x': [1, 2], 'y': [3.5, 4.5]})
f2 = pd.DataFrame({'y': [9.5], 'z': ['q']})
print(pd.concat([f1, f2]))
print(pd.concat([f1, f2], ignore_index=True))
print(pd.concat([f1, f2], join='inner'))
print(pd.concat([f1, f2], keys=['A', 'B']))
print(pd.concat([f1, f1 * 10], axis=1))
print(pd.concat([f1, pd.DataFrame({'w': [7, 8, 9]}, index=[1, 2, 3])], axis=1))
print(pd.concat([f1, pd.DataFrame({'w': [7, 8, 9]}, index=[1, 2, 3])], axis=1, join='inner'))
