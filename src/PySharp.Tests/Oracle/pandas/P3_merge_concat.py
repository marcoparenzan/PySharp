import pandas as pd

a = pd.DataFrame({'k': ['x', 'y', 'z', 'x'], 'va': [1, 2, 3, 4]})
b = pd.DataFrame({'k': ['x', 'z', 'w'], 'vb': [10.0, 30.0, 40.0]})
print(pd.merge(a, b, on='k'))
print(pd.merge(a, b, on='k', how='left'))
print(pd.merge(a, b, on='k', how='right'))
print(pd.merge(a, b, on='k', how='outer'))
print(a.merge(b, on='k', how='inner'))
print(a.merge(b))
print(pd.merge(a, b, on='k', how='outer', indicator=True))
