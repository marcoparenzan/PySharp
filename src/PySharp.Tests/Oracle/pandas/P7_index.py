print(df.join(df2, rsuffix='_2', how='outer').head(4))
print(pd.concat([df, df2]).sort_index().head(4))
print(df.truncate(before='2021-03-02', after='2021-03-04') if hasattr(df, 'truncate') else '')
print(df.between_time('00:00', '12:00').shape if False else '')
