print(s.index.to_series().diff().head(3))

df = pd.DataFrame({'a': np.arange(6), 'b': np.arange(6) * 10.0}, index=pd.date_range('2021-03-01', periods=6, freq='D'))
print(df)
print(df['2021-03-02':'2021-03-04'])
print(df.loc['2021-03-03'])
print(df.loc['2021-03-03', 'b'])
print(df.loc['2021-03'])
print(df.index.dayofweek.tolist())
print(df[df.index.dayofweek < 3])
print(df.index.is_monotonic_increasing)
print(df.rolling('3D').sum())
print(df.rolling('2D').mean())
print(df['a'].rolling('3D').max())
print(df.rolling(2).sum())
print(df.groupby(df.index.month).sum())
print(df.groupby(df.index.dayofweek).mean())
print(df.index.to_series().dt.day_name().tolist())
print(df.sort_index(ascending=False))
print(df.index.equals(df.index.copy()))
print(df.tail(2).index.tolist())
print(df.at[pd.Timestamp('2021-03-02'), 'a'])
print(df.first_valid_index(), df.last_valid_index())
df2 = df.copy()
df2.index = df2.index + pd.Timedelta(hours=6)
print(df2)
