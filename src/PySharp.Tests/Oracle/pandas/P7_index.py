print(s[:'2020-01-30 12:00'])
print(s.loc['2020-02-01'])
print(s.loc[pd.Timestamp('2020-01-31')])
print(s.loc[pd.Timestamp('2020-01-31'):pd.Timestamp('2020-02-01')])
print(s[s > 5])
print(s.index[0], s.index[-1])
print(s.index.min(), s.index.max())
print(s.index.get_loc('2020-01-31 12:00'))
print(pd.Timestamp('2020-01-31') in s.index)
print('2020-01-31 12:00' in s.index)
