import pandas as pd
p = pd.Period('2020-01', '2M')
print(repr(p), str(p), p.ordinal, p.freqstr, p.start_time, p.end_time)
print(p + 1, p - 1, p + 3)
print(pd.Period('2020-05', '2M') - p)
print(pd.period_range('2020-01', periods=4, freq='2M'))
r = pd.period_range('2020-01', periods=4, freq='3M')
print(r.dtype, r.freq, r.freqstr, r.start_time, r.end_time)
print(pd.Period('2020-03-18', '3D'), pd.Period('2020-03-18', '3D').end_time, pd.Period('2020-03-18 10:20', '15min'), pd.Period('2020-03-18 10:20', '15min').end_time)
print(pd.Period('2020-01', '2M') == pd.Period('2020-01', 'M'))
print(pd.Period('2020-01', '2M').asfreq('D'), pd.Period('2020-01', '2M').asfreq('D', 'start'))
print(pd.Period('2020-03-18', 'M').asfreq('2M'))
print(pd.Timestamp('2020-04-18').to_period('2M'), pd.Timestamp('2020-03-18').to_period('3M'))
print(pd.Series(pd.date_range('2020-01-01', periods=5, freq='45D')).dt.to_period('2M'))
print(pd.Series([1, 2, 3], index=pd.period_range('2020-01', periods=3, freq='2M')))
print(pd.period_range('2020-01', '2020-09', freq='3M'))
print(pd.period_range(end='2020-12', periods=3, freq='4M'))
print(pd.period_range('2020-01', periods=3, freq='2M').shift(1))
