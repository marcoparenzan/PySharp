dt = pd.date_range('2021-01-15', periods=6, freq='45D')
print(dt.to_period('M'))
print(pd.Series(range(6), index=dt).to_period('M'))
print(pd.DataFrame({'a': range(6)}, index=dt).to_period('Q'))
print(pd.DataFrame({'when': dt, 'v': range(6)}).assign(per=lambda d: d['when'].dt.to_period('M')))
df = pd.DataFrame({'when': dt, 'v': range(6)})
df['mon'] = df['when'].dt.to_period('M')
print(df.groupby('mon')['v'].sum())
print(df.groupby('mon').size())
print(df['mon'].value_counts().sort_index())
print(df.sort_values('mon', ascending=False).head(3))
print(df['mon'].astype(str).tolist())
print(df['mon'].dt.to_timestamp().tolist()[:2])
print(df['mon'].astype('period[Q]').tolist()[:2])
print(df['mon'] + 1)
print((df['mon'] - df['mon'].iloc[0]).tolist())
print(df['mon'].diff().tolist())
print(df.set_index('mon').head(3))
print(df['mon'].unique())
print(df['mon'].isin([pd.Period('2021-01', 'M')]).tolist())
print(df['mon'].nunique(), df['mon'].min(), df['mon'].max())
print(df['mon'].dt.strftime('%b-%Y').tolist())
print(df['mon'].dt.year.tolist(), df['mon'].dt.month.tolist(), df['mon'].dt.days_in_month.tolist())
print(df.dtypes)
print(df.describe(include='all') if False else '')
