import numpy as np
import pandas as pd

m = pd.period_range('2021-01', periods=14, freq='M')
s = pd.Series(np.arange(14.0), index=m)
print(s.head(3))
print(s['2021'])
print(s['2022'].sum())
print(s['2021-11':'2022-02'])
print(s.loc['2021-06'])
print(s.index.min(), s.index.max(), s.index.is_monotonic_increasing)
print(s.groupby(s.index.year).sum())
print(s.groupby(s.index.quarter).mean())
print(s.index.asfreq('Q'))
print(s.index.asfreq('Y'))
print(s.index.shift(2)[:3])
print(m[:3].to_timestamp().freq, m[:3].to_timestamp(how='end'))
print(s.to_timestamp().head(3))
print(s.resample('QE').sum() if False else '')
