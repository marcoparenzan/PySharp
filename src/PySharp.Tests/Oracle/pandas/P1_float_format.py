import pandas as pd

print(pd.DataFrame({'x': [1.0, 2.5, 3.14159265358979], 'y': [100.0, 0.001, 12345.6789]}))
print(pd.DataFrame({'x': [0.00001234, 1.0, 2.0]}))
print(pd.DataFrame({'x': [1234567.891, 2.0]}))
print(pd.DataFrame({'x': [1e-7, 1e7]}))
print(pd.DataFrame({'x': [float('nan'), 1.0, float('inf'), -float('inf')]}))
print(pd.DataFrame({'x': [123456789.0, 1.0]}))
print(pd.DataFrame({'x': [-0.5, 0.5, 10.0]}))
print(pd.Series([1.0, 2.0, 3.0]))
print(pd.Series([0.1 + 0.2, 1 / 3, 2 / 3]))
print(pd.Series([1e100, 1.0]))
print(pd.Series([12345678.9, 1.5]))
print(pd.Series([1, 2, 3], dtype='float32'))
print(pd.Series([0.1, 0.2], dtype='float32'))
pd.set_option('display.precision', 3)
print(pd.Series([3.14159265, 2.71828]))
pd.reset_option('display.precision')
print(pd.Series([3.14159265, 2.71828]))
