import numpy as np
x = np.array([0.1, 0.2, 0.3], dtype=np.float32)
print(x, x.dtype)
print(repr(x))
print(x * 3)
print(x + 0.1)
print(x.sum(), x.mean(), x.std())
print(x.astype(np.float64))
print(np.float32(0.1), repr(np.float32(0.1)), float(np.float32(0.1)))
print(np.float32(1) / 3)
print(np.arange(5, dtype=np.float32) / 3)
print(np.linspace(0, 1, 5, dtype=np.float32))
print((x * 1000).round(2))
print(np.zeros(3, dtype=np.float32) + 1.5)
print(np.array([1, 2, 3], dtype=np.float16) / 3)
