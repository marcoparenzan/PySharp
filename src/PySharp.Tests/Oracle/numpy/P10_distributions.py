import numpy as np

rng = np.random.default_rng(7)
print(rng.standard_exponential(8))
print(rng.exponential(2.5, 6))
print(rng.exponential())
print(rng.standard_gamma(0.5, 6))
print(rng.standard_gamma(3.0, 6))
print(rng.gamma(2.0, 3.0, 8))
print(rng.gamma(0.3, 1.5, 5))
print(rng.gamma(shape=9.5, scale=0.1, size=(2, 3)))
print(rng.poisson(3.2, 12))
print(rng.poisson(0.4, 12))
print(rng.poisson(30, 12))
print(rng.poisson(250.5, 8))
print(rng.poisson(10, 6))
print(rng.poisson(0))
print(rng.poisson(30, size=(2, 3)))
big = np.random.default_rng(123)
print(big.exponential(1.0, 5000).sum())
print(big.poisson(18.0, 5000).sum())
print(big.gamma(4.0, 2.0, 5000).sum())
print(np.random.default_rng(99).standard_exponential(3000).mean())
