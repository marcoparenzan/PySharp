import numpy as np
x = np.array([-2.5, -1.5, -0.5, 0.5, 1.5, 2.5])
print(np.round(x), np.floor(x), np.ceil(x), np.trunc(x), np.rint(x), np.sign(x), np.abs(x))
print(np.round(np.array([1.234, 5.678, -0.001]), 2))
print(np.sqrt(np.array([1, 4, 9])), np.exp(np.array([0, 1])), np.log(np.array([1, np.e])), np.log10(np.array([1, 10, 100])))
print(np.sin(np.linspace(0, np.pi, 5)), np.cos(np.linspace(0, np.pi, 5)))
print(np.degrees(np.pi), np.radians(180), np.arctan2(1, 1), np.hypot(3, 4))
print(np.power(2, np.arange(5)), 2 ** np.arange(5), np.arange(5) ** 2, np.arange(1, 5) ** 0.5)
