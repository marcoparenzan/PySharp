print(np.array([5, -5]) // 3, np.array([5, -5]) % 3, np.array([5.5, -5.5]) // 2, np.array([5.5, -5.5]) % 2)
print(np.array([1, 2, 3]) / np.array([2, 2, 2]), np.array([1, 2, 3]) * 1.5, 10 - np.arange(3), 1 / np.arange(1, 4))
print(np.array([1e-5, 1.0]), np.array([1e10, 1.0]), np.array([1e-10, 1.0]), np.array([0.1, 0.25, 100.0]), np.array([1e16, 1.0]))
print(np.array([np.nan, np.inf, -np.inf, 1.5]), np.array([[1.5, np.nan], [2.0, 3.0]]))
print(np.arange(30).reshape(3, 10) * 1.5)
print(np.arange(100.0).reshape(10, 10)[:3])
print(np.arange(2000).reshape(40, 50))
print(repr(np.arange(3)), repr(np.arange(3.0)), repr(np.array([True, False])), repr(np.zeros((2, 0))))
