import numpy as np
import cv2
img = np.zeros((20, 30, 3), np.uint8)
r = cv2.rectangle(img, (2, 3), (12, 9), (255, 0, 0), 1)
print(r is img, img[3, 2:13, 0], img[:, :, 0].sum())
cv2.rectangle(img, (14, 3), (20, 9), (0, 255, 0), -1)
cv2.circle(img, (8, 14), 4, (0, 0, 255), 1)
cv2.circle(img, (22, 14), 3, (255, 255, 255), cv2.FILLED)
cv2.line(img, (0, 19), (29, 0), (10, 20, 30), 1)
cv2.line(img, (0, 0), (29, 19), (200, 100, 50), 2, cv2.LINE_AA)
print(img.sum(axis=(0, 1)), img[:, :, 1].sum(), img[:, :, 2].sum())
cv2.arrowedLine(img, (1, 10), (15, 10), (255, 255, 0), 1)
cv2.ellipse(img, (15, 10), (8, 4), 30, 0, 360, (0, 255, 255), 1)
cv2.putText(img, "Hi", (2, 18), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)
cv2.drawMarker(img, (25, 5), (255, 0, 255), cv2.MARKER_CROSS, 5, 1)
print(img.sum(axis=(0, 1)), np.count_nonzero(img))
tri = np.array([[5, 2], [25, 2], [15, 12]], np.int32)
g = np.zeros((15, 30), np.uint8)
cv2.fillPoly(g, [tri], 255)
print(np.count_nonzero(g), g.sum())
cv2.polylines(g, [tri.reshape(-1, 1, 2)], True, 90, 1)
print(np.count_nonzero(g), g.sum())
gray = np.random.default_rng(1).integers(0, 256, (16, 16), dtype=np.uint8)
ok, buf = cv2.imencode(".png", gray)
print(ok, buf.dtype, buf.ndim, len(buf), np.array_equal(cv2.imdecode(buf, cv2.IMREAD_GRAYSCALE), gray))
col = np.random.default_rng(2).integers(0, 256, (16, 16, 3), dtype=np.uint8)
ok, jb = cv2.imencode(".jpg", col, [cv2.IMWRITE_JPEG_QUALITY, 90])
dec = cv2.imdecode(jb, cv2.IMREAD_COLOR)
print(ok, len(jb), dec.shape, int(dec.astype(int).sum()), dec[0, :3])
ok, pb = cv2.imencode(".png", col, [cv2.IMWRITE_PNG_COMPRESSION, 9])
print(ok, len(pb), np.array_equal(cv2.imdecode(pb, cv2.IMREAD_UNCHANGED), col))
print(cv2.imread("does_not_exist.png"), cv2.imdecode(np.frombuffer(b"nonsense", np.uint8), 1))
