import numpy as np
import cv2
rng = np.random.default_rng(11)
gray = rng.integers(0, 256, (12, 14), dtype=np.uint8)
col = rng.integers(0, 256, (12, 14, 3), dtype=np.uint8)
k = np.array([[1, 0, -1], [2, 0, -2], [1, 0, -1]], np.float32)
print(cv2.filter2D(gray, -1, k)[:3, :6], cv2.filter2D(gray, cv2.CV_64F, k / 4)[:2, :4], cv2.filter2D(col, -1, np.ones((3, 3), np.float32) / 9)[:2, :3])
print(cv2.GaussianBlur(gray, (5, 5), 0)[:3, :6], cv2.GaussianBlur(gray, (3, 3), 1.5, borderType=cv2.BORDER_REPLICATE)[:2, :5], cv2.GaussianBlur(col.astype(np.float32), (5, 5), 1)[:2, :2])
print(cv2.getGaussianKernel(5, 1.0).T, cv2.getGaussianKernel(3, 0, cv2.CV_32F).T, cv2.getGaussianKernel(5, 1.0).shape)
print(cv2.boxFilter(gray, -1, (3, 3))[:2, :5], cv2.boxFilter(gray, cv2.CV_32F, (3, 3), normalize=False)[:2, :4], cv2.blur(gray, (5, 5))[:2, :5])
print(cv2.medianBlur(gray, 3)[:3, :6], cv2.medianBlur(gray, 5)[:2, :5], cv2.bilateralFilter(col, 5, 50, 50)[:2, :3])
print(cv2.Sobel(gray, cv2.CV_64F, 1, 0)[:2, :5], cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=5)[:2, :4], cv2.Sobel(gray, cv2.CV_16S, 1, 1, ksize=3)[:2, :4])
print(cv2.Scharr(gray, cv2.CV_32F, 1, 0)[:2, :4], cv2.Laplacian(gray, cv2.CV_64F)[:2, :4], cv2.Laplacian(gray, cv2.CV_8U, ksize=3)[:2, :6])
print(cv2.Canny(gray, 50, 150), cv2.Canny(gray, 50, 150, L2gradient=True).sum(), cv2.Canny(gray, 100, 200, apertureSize=5).sum())
print(cv2.pyrDown(gray), cv2.pyrUp(gray).shape, cv2.pyrUp(gray)[:2, :6], cv2.pyrDown(col).shape)
print(np.round(cv2.getGaborKernel((5, 5), 2.0, 0.5, 4.0, 0.5), 6), cv2.getGaborKernel((3, 3), 1.0, 0.0, 2.0, 1.0, 0, cv2.CV_32F).dtype)
mag, ang = cv2.cartToPolar(np.array([[3.0, 0.0]]), np.array([[4.0, -1.0]]))
print(mag, ang, cv2.cartToPolar(np.array([[1.0]]), np.array([[1.0]]), angleInDegrees=True)[1])
d = cv2.dct(gray[:8, :8].astype(np.float32))
print(np.round(d[:2, :4], 4), np.allclose(cv2.idct(d), gray[:8, :8].astype(np.float32), atol=1e-3))
bw = np.zeros((9, 9), np.uint8)
bw[3:6, 3:6] = 255
print(np.round(cv2.distanceTransform(bw, cv2.DIST_L2, 3), 4), np.round(cv2.distanceTransform(bw, cv2.DIST_L1, 3), 3)[3, :], cv2.distanceTransform(bw, cv2.DIST_L2, 5).dtype)

M = cv2.getRotationMatrix2D((6.5, 5.5), 30, 0.8)
print(np.round(M, 6), M.dtype)
print(cv2.warpAffine(gray, M, (14, 12))[:3, :6], cv2.warpAffine(gray, M, (20, 10), flags=cv2.INTER_NEAREST)[:2, :6], cv2.warpAffine(col, M, (14, 12), borderValue=(10, 20, 30))[:2, :3], cv2.warpAffine(gray, M, (14, 12), flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_REFLECT)[:2, :5])
src = np.float32([[0, 0], [10, 0], [0, 10]])
dst = np.float32([[1, 2], [12, 3], [2, 14]])
A = cv2.getAffineTransform(src, dst)
print(np.round(A, 6), np.round(cv2.invertAffineTransform(A), 6))
s4 = np.float32([[0, 0], [10, 0], [10, 10], [0, 10]])
d4 = np.float32([[1, 1], [9, 2], [11, 12], [0, 9]])
H = cv2.getPerspectiveTransform(s4, d4)
print(np.round(H, 6), H.dtype, cv2.warpPerspective(gray, H, (14, 12))[:3, :6], cv2.warpPerspective(gray, H, (14, 12), flags=cv2.INTER_NEAREST)[:2, :6])
print(np.round(cv2.perspectiveTransform(s4.reshape(-1, 1, 2), H), 4).reshape(-1, 2))

shape = np.zeros((20, 20), np.uint8)
cv2.rectangle(shape, (3, 4), (12, 9), 255, -1)
cv2.circle(shape, (14, 14), 3, 255, -1)
m = cv2.moments(shape)
print(list(m.keys())[:6], m["m00"], m["m10"], m["m01"], round(m["mu20"], 4), round(m["nu11"], 8))
print(np.round(cv2.HuMoments(m).ravel(), 10), cv2.moments(shape, binaryImage=True)["m00"])
cs, hier = cv2.findContours(shape, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
print(len(cs), [c.shape for c in cs], hier.shape, cs[0].dtype, cs[0].ravel()[:8], cv2.contourArea(cs[0]), cv2.arcLength(cs[0], True))
cs2, h2 = cv2.findContours(shape, cv2.RETR_TREE, cv2.CHAIN_APPROX_NONE)
print(len(cs2), h2[0].tolist(), [len(c) for c in cs2])

print(np.round(cv2.cornerHarris(gray.astype(np.float32), 2, 3, 0.04)[:2, :4], 2), np.round(cv2.cornerMinEigenVal(gray.astype(np.float32), 3)[:2, :4], 2))
pts = cv2.goodFeaturesToTrack(gray, 10, 0.01, 2)
print(pts.shape, pts.dtype, pts[:3, 0].tolist(), cv2.goodFeaturesToTrack(np.zeros((8, 8), np.uint8), 5, 0.1, 1))
edges = cv2.Canny(shape, 50, 150)
print(cv2.HoughLines(edges, 1, np.pi / 180, 5).shape, cv2.HoughLinesP(edges, 1, np.pi / 180, 5, minLineLength=4, maxLineGap=2).shape, cv2.HoughLines(np.zeros((8, 8), np.uint8), 1, 0.1, 5))
cc = cv2.HoughCircles(cv2.GaussianBlur(shape, (5, 5), 1), cv2.HOUGH_GRADIENT, 1, 5, param1=100, param2=6, minRadius=2, maxRadius=6)
print(None if cc is None else (cc.shape, cc.dtype))
