    private double StandardGammaDouble(double shape)
    {
        if (shape == 1.0) return StandardExponentialDouble();
        if (shape == 0.0) return 0.0;
        if (shape < 1.0)
        {
            while (true)
            {
                double u = _bits.NextDouble();
                double v = StandardExponentialDouble();
                if (u <= 1.0 - shape)
                {
                    double x = Math.Pow(u, 1.0 / shape);
                    if (x <= v) return x;
                }
                else
                {
                    double y = -Math.Log((1 - u) / shape);
                    double x = Math.Pow(1.0 - shape + shape * y, 1.0 / shape);
                    if (x <= v + y) return x;
                }
            }
        }
        double b = shape - 1.0 / 3.0;
        double c = 1.0 / Math.Sqrt(9 * b);
        while (true)
        {
            double x, v;
            do { x = StandardNormalDouble(); v = 1.0 + c * x; } while (v <= 0.0);
            v = v * v * v;
            double u = _bits.NextDouble();
            if (u < 1.0 - 0.0331 * (x * x) * (x * x)) return b * v;
            if (Math.Log(u) < 0.5 * x * x + b * (1.0 - v + Math.Log(v))) return b * v;
        }
    }

    public NDArray StandardGamma(double shape, int[]? size = null) => Fill(size, () => StandardGammaDouble(shape));

    public NDArray Gamma(double shape, double scale, int[]? size = null) => Fill(size, () => scale * StandardGammaDouble(shape));

