    /// <summary>numpy's <c>random_loggam</c> (Stirling series with upward recurrence below 7).</summary>
    private static double LogGamma(double x)
    {
        if (x == 1.0 || x == 2.0) return 0.0;
        long n = x < 7.0 ? (long)(7 - x) : 0;
        double x0 = x + n;
        double x2 = 1.0 / x0 * (1.0 / x0);
        const double lg2pi = 1.8378770664093453e+00;
        double gl0 = LogGammaCoef[9];
        for (int k = 8; k >= 0; k--) { gl0 *= x2; gl0 += LogGammaCoef[k]; }
        double gl = gl0 / x0 + 0.5 * lg2pi + (x0 - 0.5) * Math.Log(x0) - x0;
        if (x < 7.0)
            for (long k = 1; k <= n; k++) { gl -= Math.Log(x0 - 1.0); x0 -= 1.0; }
        return gl;
    }

    private long PoissonDouble(double lam)
    {
        if (lam >= 10.0)
        {
            double slam = Math.Sqrt(lam), loglam = Math.Log(lam);
            double b = 0.931 + 2.53 * slam;
            double a = -0.059 + 0.02483 * b;
            double invalpha = 1.1239 + 1.1328 / (b - 3.4);
            double vr = 0.9277 - 3.6224 / (b - 2);
            while (true)
            {
                double u = _bits.NextDouble() - 0.5;
                double v = _bits.NextDouble();
                double us = 0.5 - Math.Abs(u);
                long k = (long)Math.Floor((2 * a / us + b) * u + lam + 0.43);
                if (us >= 0.07 && v <= vr) return k;
                if (k < 0 || (us < 0.013 && v > us)) continue;
                if (Math.Log(v) + Math.Log(invalpha) - Math.Log(a / (us * us) + b) <= -lam + k * loglam - LogGamma(k + 1)) return k;
            }
        }
        if (lam == 0.0) return 0;
        double enlam = Math.Exp(-lam);
        long x = 0;
        double prod = 1.0;
        while (true)
        {
            double u = _bits.NextDouble();
            prod *= u;
            if (prod > enlam) x++; else return x;
        }
    }

