    private double StandardExponentialDouble()
    {
        while (true)
        {
            ulong ri = _bits.Next64();
            ri >>= 3;
            int idx = (int)(ri & 0xff);
            ri >>= 8;
            double x = ri * ExpWe[idx];
            if (ri < ExpKe[idx]) return x;
            if (idx == 0) return ZigExpR - Math.Log(1.0 - _bits.NextDouble());
            if ((ExpFe[idx - 1] - ExpFe[idx]) * _bits.NextDouble() + ExpFe[idx] < Math.Exp(-x)) return x;
        }
    }

