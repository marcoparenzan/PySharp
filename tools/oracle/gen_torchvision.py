"""Copies the pure-Python parts of torchvision (BSD-3-Clause, https://github.com/pytorch/vision) that PySharp.Torch needs from the oracle
venv into src/PySharpLib.Torch/py/, rewriting relative imports to absolute ones. Files that depend on compiled extensions or on PIL are
hand-written instead (see the *.py files in that folder without the "GENERATED" header).

    tools/oracle/.venv/Scripts/python.exe tools/oracle/gen_torchvision.py
"""
import os
