HEADER = ("# GENERATED by tools/oracle/gen_torchvision.py from torchvision {ver} ({rel}); BSD-3-Clause, Copyright (c) Soumith Chintala 2016.\n"
          "# Do not edit by hand: change the generator or add a hand-written override instead.\n")


def absolutize(text, module):
    pkg = module.rsplit(".", 1)[0]  # the file is a plain module: its package is the parent

    def fix(m):
        dots, rest = m.group(1), m.group(2)
        parts = pkg.split(".")
        base = parts[: len(parts) - (len(dots) - 1)]
        return "from " + ".".join(base + ([rest] if rest else [])) + " import "

    return re.sub(r"^from (\.+)([\w.]*) import ", fix, text, flags=re.M)


def main():
    import torchvision
    only = sys.argv[1:]
    for rel, module in FILES.items():
        if only and not any(o in module for o in only):
            continue
        path = os.path.join(src, *rel.split("/"))
        if not os.path.exists(path):
            print("missing", rel)
            continue
        text = open(path, encoding="utf-8").read()
        text = absolutize(text, module)
        with open(os.path.join(out, module + ".py"), "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER.format(ver=torchvision.__version__, rel=rel) + text)
        print("wrote", module)


if __name__ == "__main__":
    main()
