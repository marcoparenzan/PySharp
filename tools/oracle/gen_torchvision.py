root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
src = os.path.join(os.path.dirname(sys.executable), "..", "Lib", "site-packages", "torchvision")
src = os.path.normpath(src)
out = os.path.join(root, "src", "PySharpLib.Torch", "py")

# real path (relative to torchvision/) -> module name
